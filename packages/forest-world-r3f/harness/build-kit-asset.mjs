// build-kit-asset.mjs — regenerate `src/kit-asset.ts` from the committed `.glb`.
//
// ⚠⚠ WHY THE ASSET HAS TO BE EMBEDDED AT ALL, and it is not a style choice.
// `packages/forest-world-r3f/src` is MIRRORED into the public storytree-web repo by
// `pnpm sync:web-engine`, and `isEngineSource` (`packages/cli/src/web-engine-sync.ts`) carries
// `.ts` and `.tsx` AND NOTHING ELSE. `check:web-engine` blocks until the mirror matches. So a
// `src/` module that fetched `/assets/dressing-kit.glb` would work in the parent's own harness and
// 404 in the public engine copy — silently, only for visitors, and only once somebody mounted it.
// A `.ts` module is the one shape that crosses the seam that exists.
//
// THE COST IS MEASURED, NOT ARGUED (2026-08-30, `node:zlib` brotli quality 11):
//
//   raw .glb            162,748 B on disk   110,487 B brotli
//   base64 in a .ts     217,034 B on disk   124,567 B brotli   ← +12.7% over the wire
//
// The alternative — teaching the sync to carry binary assets — buys back 14,080 B of wire and
// costs a change to a pure, tested module, its gate rung, and a URL every consuming bundler has to
// resolve. It is written up beside the number rather than taken silently; if the payload ever
// matters more than the wiring, that is the route.
//
// ⚠ THE `.glb` STAYS THE ONE SOURCE OF TRUTH. This writes a PROJECTION of it (the ADR-0051/0052
// generated-view + drift pattern the repo already uses): `src/kit-asset.test.ts` re-derives the
// base64 from the committed file and fails if the two disagree, so the pair cannot drift the way
// this package's three status palettes once did. Re-export the kit, run this, commit both.
//
//   node --import ../../scripts/tsx-cache-off.mjs --import tsx harness/build-kit-asset.mjs

import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const GLB = join(HERE, 'assets', 'dressing-kit.glb');
const OUT = join(HERE, '..', 'src', 'kit-asset.ts');

const bytes = readFileSync(GLB);
const base64 = bytes.toString('base64');
const sha256 = createHash('sha256').update(bytes).digest('hex');

const header = `// kit-asset.ts — THE BOUGHT KIT, EMBEDDED. @generated by \`harness/build-kit-asset.mjs\`.
//
// ⚠ DO NOT EDIT THE LITERAL. The source of truth is \`harness/assets/dressing-kit.glb\`; this is a
// projection of it, and \`kit-asset.test.ts\` re-derives the base64 from that file and fails if the
// two disagree. Re-export the kit, re-run the generator, commit both.
//
// ⚠⚠ IT IS EMBEDDED BECAUSE THE WEB SYNC CARRIES ONLY \`.ts\` AND \`.tsx\`
// (\`isEngineSource\`, \`packages/cli/src/web-engine-sync.ts\`). A \`src/\` module that fetched
// \`/assets/dressing-kit.glb\` would work in the parent harness and 404 in the public engine copy —
// silently, only for visitors. Measured cost of the embedding, brotli q11: 124,567 B against the
// raw file's 110,487, i.e. **+12.7% over the wire** for an asset that cannot go missing.
`;

const body = `
/** The kit as committed: SHA-256 of \`harness/assets/dressing-kit.glb\`. Held by the drift test —
 *  a re-export that changed the asset without regenerating this module is caught here rather than
 *  by an island that quietly draws a different tree. */
export const KIT_ASSET_SHA256 = '${sha256}';

/** Bytes of the \`.glb\` itself — what a visitor would download if it were served as a file, and
 *  the figure every payload table on this arc is stated in. NOT the size of this module. */
export const KIT_ASSET_BYTES = ${bytes.length};

/** The \`.glb\`, base64. One literal on purpose: a chunked array would need joining at runtime and
 *  would give the mutation rung one survivor per chunk to argue about. */
const KIT_ASSET_BASE64 =
  '${base64}';

/**
 * DECODE THE KIT into the \`ArrayBuffer\` \`GLTFLoader.parseAsync\` wants.
 *
 * ⚠ \`atob\` RETURNS A BINARY STRING, ONE BYTE PER CHAR, and it is the only browser-safe decoder
 * available here — \`Buffer\` is Node's. Writing the bytes out through \`charCodeAt\` is therefore
 * the decode, not a copy that could be skipped: a \`TextEncoder\` over the same string would
 * UTF-8-encode every char above 0x7f into two bytes and corrupt about half the asset, in a way
 * that surfaces as a glTF parse error rather than as anything naming the cause.
 *
 * ⚠ \`Uint8Array.from\` RATHER THAN AN INDEXED LOOP, deliberately. A \`for (let i = 0; …; i += 1)\`
 * over 217,000 chars carries mutants that flip \`+=\` to \`-=\` and \`<\` to \`>\`; neither fails an
 * assertion, both run forever, and \`check:mutation-diff\` scores a hang as UNPROVEN — credited to
 * nobody and redding the rung. There is no counter here to mutate.
 */
export function decodeKitAsset(): ArrayBuffer {
  return Uint8Array.from(atob(KIT_ASSET_BASE64), (c) => c.charCodeAt(0)).buffer;
}
`;

writeFileSync(OUT, header + body, 'utf8');
process.stdout.write(
  `wrote ${OUT}\n  glb ${bytes.length} B · sha256 ${sha256}\n  base64 ${base64.length} chars\n`,
);
